#!/usr/bin/env node
// Puts the flag collections into index.html, so the page needs no second request to show them.
//
//   node tools/bundle.mjs            # rewrite the generated block in index.html
//   node tools/bundle.mjs --check    # exit 1 if the block does not match catalog/flags/*.json
//
// catalog/flags/*.json stays the source of truth and is never changed here. The block holds only what
// the panel shows (the description is the same short text the page would show), and it is the only
// part of index.html this script touches. The trimming rules are read from the page itself, so
// there is one copy of them.
import { readFileSync, writeFileSync, readdirSync, renameSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(ROOT, 'index.html');
const START = '<!-- ▸ data: flags (generated by tools/bundle.mjs, do not edit) -->';
const END = '<!-- end of generated flags -->';
const FACTS_START = '<!-- ▸ data: model facts (generated by tools/bundle.mjs, do not edit) -->';
const FACTS_END = '<!-- end of generated facts -->';
const FACT_KEYS = ['billions', 'gib', 'heads', 'kvHeads', 'maxCtx', 'kv', 'arch', 'type', 'custom', 'quant', 'recipe'];
const ORDER = ['vllm', 'vllm-omni', 'sglang', 'sglang-diffusion', 'trtllm', 'tgi', 'llama', 'ollama', 'mlx'];

export function lean(root = ROOT) {
  const page = readFileSync(join(root, 'index.html'), 'utf8');
  const a = page.indexOf('var HELP_FILLER');
  const b = page.indexOf('function flagLine(');
  if (a < 0 || b < a) throw new Error('cannot find the description rules in index.html');
  const ctx = vm.createContext({});
  vm.runInContext(page.slice(a, b), ctx);
  const dir = join(root, 'catalog', 'flags');
  const names = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.replace('.json', ''));
  names.sort((x, y) => (ORDER.indexOf(x) + 1 || 99) - (ORDER.indexOf(y) + 1 || 99) || x.localeCompare(y));
  const out = {};
  for (const engine of names) {
    const d = JSON.parse(readFileSync(join(dir, engine + '.json'), 'utf8'));
    out[engine] = {
      source: d.source,
      fetched: d.fetched,
      ...(d.release ? { release: d.release } : {}),
      ...(d.support ? { support: d.support } : {}),
      count: d.count,
      sections: d.sections.map((s) => ({
        title: s.title,
        flags: s.flags.map((f) => {
          const help = ctx.flagHelpText(f);
          return {
            name: f.name,
            ...(f.aliases && f.aliases.length ? { aliases: f.aliases } : {}),
            ...(f.negation ? { negation: f.negation } : {}),
            ...(f.choices && f.choices.length ? { choices: f.choices } : {}),
            ...(f.default != null ? { default: f.default } : {}),
            ...(f.value ? { value: f.value } : {}),
            ...(help ? { help } : {}),
          };
        }),
      })),
    };
  }
  return out;
}

export function block(root = ROOT) {
  const data = lean(root);
  const lines = Object.keys(data).map((k) => JSON.stringify({ [k]: data[k] }).replace(/</g, '\\u003c'));
  // one engine per line: a change to one engine is one changed line in the diff
  return `${START}\n<script type="application/json" id="flagData">\n${lines.join('\n')}\n</script>\n${END}\n`;
}

export function factsBlock(root = ROOT) {
  const facts = JSON.parse(readFileSync(join(root, 'catalog', 'facts.json'), 'utf8'));
  const lines = Object.keys(facts).sort().map((ref) => {
    const f = {};
    for (const k of FACT_KEYS) if (facts[ref][k] !== undefined && facts[ref][k] !== null) f[k] = facts[ref][k];
    return JSON.stringify({ [ref]: f }).replace(/</g, '\\u003c');
  });
  return `${FACTS_START}\n<script type="application/json" id="factData">\n${lines.join('\n')}\n</script>\n${FACTS_END}\n`;
}

// What the page should contain, as [start marker, end marker, text] spans.
function spans(root) {
  return [[START, END, block(root)], [FACTS_START, FACTS_END, factsBlock(root)]];
}

export function current(page, start = START, end = END) {
  const i = page.indexOf(start), j = page.indexOf(end);
  if (i < 0 || j < i) return null;
  return page.slice(i, j + end.length + 1);
}

function main() {
  const root = process.env.MODULAR_ROOT || ROOT;
  const file = join(root, 'index.html');
  let page = readFileSync(file, 'utf8');
  const wanted = spans(root);
  if (process.argv.includes('--check')) {
    const off = wanted.filter(([a, b, text]) => current(page, a, b) !== text);
    if (!off.length) return console.log('data bundle: in sync');
    console.log('data bundle: index.html differs from catalog/ for: ' + off.map(([a]) => (a === START ? 'flags' : 'model facts')).join(', '));
    console.log('fix: python3 -m librarian sync');
    process.exit(1);
  }
  let changed = false;
  for (const [a, b, text] of wanted) {
    const have = current(page, a, b);
    if (have === text) continue;
    changed = true;
    if (have !== null) page = page.replace(have, () => text);
    else {
      const anchor = '  <script>\n    /* ▸ js: data';
      if (!page.includes(anchor)) throw new Error('cannot find where to put the generated block');
      page = page.replace(anchor, () => text + anchor);
    }
  }
  if (!changed) return console.log('data bundle: already in sync');
  writeFileSync(file + '.tmp', page);
  renameSync(file + '.tmp', file); // never leave a half-written page
  console.log('data bundle: index.html updated');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
